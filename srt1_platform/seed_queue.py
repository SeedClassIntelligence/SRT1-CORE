def main():
    """Quick CLI for testing the seed queue."""
    import argparse

    parser = argparse.ArgumentParser(description="SRT-1 Seed Queue Manager")
    sub = parser.add_subparsers(dest="command")

    # Plant
    p = sub.add_parser("plant", help="Plant a new seed")
    p.add_argument("intent", help="What to build")
    p.add_argument("--source", default="cli", help="Source (cli, mobile, api)")
    p.add_argument("--priority", type=int, default=5, help="Priority 1-10")

    # List
    sub.add_parser("list", help="List all seeds")

    # Status
    s = sub.add_parser("status", help="Get seed status")
    s.add_argument("seed_id", help="Seed ID")

    # Bloom
    b = sub.add_parser("bloom", help="Mark seed as completed")
    b.add_argument("seed_id", help="Seed ID")
    b.add_argument("--summary", default="", help="Completion summary")

    # Stats
    sub.add_parser("stats", help="Show farm statistics")

    args = parser.parse_args()
    if not args.command:
        parser.print_help()
        return

    queue = SCIASeedQueue()

    if args.command == "plant":
        seed = queue.plant(args.intent, source=args.source, priority=args.priority)
        print(f"\n  {seed.stage.emoji} Seed planted: {seed.seed_id}")
        print(f"  Intent: {seed.intent}")
        print(f"  Growth: {seed.growth}%\n")

    elif args.command == "list":
        seeds = queue.list_seeds()
        if not seeds:
            print("  No seeds in the queue.")
            return
        print(f"\n  {'─' * 80}")
        for s in seeds:
            emoji = s["stage_emoji"]
            growth = f"{s['growth']}%"
            files = s["files_modified"]
            print(f"  {emoji} {s['seed_id']}  [{s['stage']}]  {growth:>4}  "
                  f"files={files}  {s['intent'][:50]}")
        print(f"  {'─' * 80}\n")

    elif args.command == "status":
        seed = queue.get_seed(args.seed_id)
        if not seed:
            print(f"  Seed {args.seed_id} not found.")
            return
        print(json.dumps(seed, indent=2))

    elif args.command == "bloom":
        seed = queue.bloom(args.seed_id, summary=args.summary)
        if seed:
            print(f"  🌸 Seed {args.seed_id} has BLOOMED!")
        else:
            print(f"  ❌ Seed not found.")

    elif args.command == "stats":
        stats = queue.get_stats()
        print(json.dumps(stats, indent=2))


if __name__ == "__main__":
    main()
